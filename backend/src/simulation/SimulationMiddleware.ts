import { Request, Response, NextFunction } from 'express';
import { simulationService } from './SimulationService.js';
import { requestActivityService } from '../services/RequestActivityService.js';
import { HttpMethod, RequestLog } from '../types/index.js';
import { config } from '../config/index.js';

export const simulationMiddleware = async (req: Request, res: Response, next: NextFunction): Promise<void> => {
  const startTime = Date.now();

  // 1. Assign or preserve X-Request-ID
  const clientReqId = req.headers['x-request-id'];
  const requestId = (typeof clientReqId === 'string' && clientReqId.trim().length > 0)
    ? clientReqId.trim()
    : `req_${Date.now()}_${Math.random().toString(36).substring(2, 8)}`;

  res.setHeader('X-Request-ID', requestId);
  res.setHeader('X-API-Version', '1.0.0');

  const fullPath = (req.originalUrl || req.url).split('?')[0];

  // Skip simulation logic for internal playground control, docs endpoints, and CORS preflight
  if (
    req.method === 'OPTIONS' ||
    fullPath.startsWith('/api/simulation') ||
    fullPath.startsWith('/api/activity') ||
    fullPath === '/openapi.json' ||
    fullPath.startsWith('/docs')
  ) {
    return next();
  }

  const method = req.method.toUpperCase() as HttpMethod;
  const matchedEp = simulationService.findMatchingEndpoint(method, fullPath);
  const serviceName = matchedEp ? matchedEp.service : 'General';
  res.setHeader('X-Service', serviceName);

  const globalState = simulationService.getGlobalState();
  const epConfig = matchedEp ? matchedEp.simulationConfig : undefined;
  const isDeactivated = Boolean(matchedEp && matchedEp.isActive === false);
  const mode = isDeactivated ? 'DEACTIVATED' : (epConfig ? epConfig.mode : 'HEALTHY');

  // Direct Chaos Triggers (Query params or X-Chaos-* headers)
  const getHeaderOrQuery = (headerKey: string, ...queryKeys: string[]): string | undefined => {
    const fromHeader = req.headers[headerKey.toLowerCase()];
    if (typeof fromHeader === 'string' && fromHeader.trim()) {
      return fromHeader.trim();
    }
    for (const q of queryKeys) {
      const fromQuery = req.query[q];
      if (typeof fromQuery === 'string' && fromQuery.trim()) {
        return fromQuery.trim();
      }
    }
    return undefined;
  };

  const directDowntime = getHeaderOrQuery('x-chaos-downtime', 'chaos_downtime', 'chaos_down', 'chaos_outage');
  const isDirectDowntime = directDowntime === 'true' || directDowntime === '1';

  const directStatusRaw = getHeaderOrQuery('x-chaos-status', 'chaos_status', 'chaos_error', 'chaos_code');
  const directStatusCode = directStatusRaw ? parseInt(directStatusRaw, 10) : undefined;
  const directStatusMessage = getHeaderOrQuery('x-chaos-message', 'chaos_message', 'chaos_msg');

  const directLatencyRaw = getHeaderOrQuery('x-chaos-latency', 'chaos_latency', 'chaos_delay');
  const directLatencyMs = directLatencyRaw ? parseInt(directLatencyRaw, 10) : undefined;

  const directSchema = getHeaderOrQuery('x-chaos-schema', 'chaos_schema', 'chaos_mutation');

  let activeSimulationMode = globalState.globalOutage ? 'GLOBAL_OUTAGE' : mode;
  if (isDirectDowntime) activeSimulationMode = 'CHAOS_DOWNTIME';
  else if (directStatusCode) activeSimulationMode = `CHAOS_STATUS_${directStatusCode}`;
  else if (directLatencyMs) activeSimulationMode = `CHAOS_LATENCY_${directLatencyMs}MS`;
  else if (directSchema) activeSimulationMode = `CHAOS_SCHEMA_${directSchema.toUpperCase()}`;
  res.setHeader('X-Simulation-Mode', activeSimulationMode);

  // Helper to record activity on response completion
  let responseBodyCaptured: any = null;
  const originalJson = res.json.bind(res);
  const originalSend = res.send.bind(res);

  const setResponseTimeHeader = () => {
    if (!res.headersSent) {
      res.setHeader('X-Response-Time', `${Date.now() - startTime}ms`);
    }
  };

  res.json = function (body: any) {
    responseBodyCaptured = body;

    // Apply schema transformation if applicable (direct override has highest priority)
    const effectiveSchema = directSchema || epConfig?.schemaVersion;
    if (effectiveSchema && body) {
      if (effectiveSchema === 'broken' || effectiveSchema === 'corrupt') {
        body = {
          unexpected: true,
          data: null,
          schemaError: 'Corrupted payload intentionally generated by chaos simulation engine',
          driftDetected: true,
          missingFields: ['id', 'name', 'price', 'category'],
        };
        responseBodyCaptured = body;
      } else if (effectiveSchema === 'v2') {
        body = transformToSchemaV2(body);
        responseBodyCaptured = body;
      } else if (effectiveSchema === 'empty') {
        body = {};
        responseBodyCaptured = body;
      }
    }

    setResponseTimeHeader();
    return originalJson(body);
  };

  res.send = function (body: any) {
    if (typeof body === 'string' && !responseBodyCaptured) {
      try {
        responseBodyCaptured = JSON.parse(body);
      } catch {
        responseBodyCaptured = body.length > 500 ? body.substring(0, 500) + '... (truncated)' : body;
      }
    }
    setResponseTimeHeader();
    return originalSend(body);
  };

  res.on('finish', () => {
    const responseTimeMs = Date.now() - startTime;

    const reqHeaders: Record<string, string> = {};
    for (const [k, v] of Object.entries(req.headers)) {
      if (k.toLowerCase() !== 'cookie' && k.toLowerCase() !== 'authorization') {
        reqHeaders[k] = Array.isArray(v) ? v.join(', ') : v || '';
      } else if (k.toLowerCase() === 'authorization') {
        reqHeaders[k] = '[REDACTED]';
      }
    }

    const resHeaders: Record<string, string> = {};
    for (const [k, v] of Object.entries(res.getHeaders())) {
      resHeaders[k] = String(v);
    }

    const log: RequestLog = {
      id: requestId,
      timestamp: new Date(startTime).toISOString(),
      method,
      path: req.path,
      url: req.originalUrl || req.url,
      service: serviceName,
      statusCode: res.statusCode,
      responseTimeMs,
      requestSize: Number(req.headers['content-length'] || 0),
      responseSize: Number(res.getHeader('content-length') || 0),
      ip: (req.headers['x-forwarded-for'] as string) || req.socket.remoteAddress || '127.0.0.1',
      userAgent: req.headers['user-agent'] || 'unknown',
      simulationMode: globalState.globalOutage ? 'GLOBAL_OUTAGE' : mode,
      error: res.statusCode >= 400 ? (responseBodyCaptured?.error?.message || `HTTP ${res.statusCode}`) : undefined,
      requestHeaders: reqHeaders,
      requestBody: req.body,
      responseHeaders: resHeaders,
      responseBody: responseBodyCaptured,
    };

    requestActivityService.record(log);
  });

  // 0. Direct Downtime injection (via query param or header)
  if (isDirectDowntime) {
    res.status(503).json({
      error: {
        code: 'SIMULATED_DOWNTIME_OUTAGE',
        message: 'Simulated service downtime: Service is completely unavailable (503 Service Unavailable).',
        status: 503,
        requestId,
        timestamp: new Date().toISOString(),
      },
    });
    return;
  }

  // 0.5. Direct HTTP Error injection (via query param or header)
  if (directStatusCode && directStatusCode >= 400 && directStatusCode <= 599) {
    res.status(directStatusCode).json({
      error: {
        code: `SIMULATED_HTTP_ERROR_${directStatusCode}`,
        message: directStatusMessage || getStandardErrorMessage(directStatusCode),
        status: directStatusCode,
        requestId,
        timestamp: new Date().toISOString(),
      },
    });
    return;
  }

  // 1.5. Deactivated endpoint check
  if (isDeactivated) {
    res.status(503).json({
      error: {
        code: 'ENDPOINT_DEACTIVATED',
        message: `Endpoint '${method} ${matchedEp!.path}' is currently DEACTIVATED in Sentinel API Playground.`,
        status: 503,
        requestId,
        timestamp: new Date().toISOString(),
      },
    });
    return;
  }

  // 2. Global Outage check
  if (globalState.globalOutage) {
    res.status(503).json({
      error: {
        code: 'GLOBAL_OUTAGE_ACTIVE',
        message: 'Global outage simulation is active across all Sentinel playground endpoints.',
        status: 503,
        requestId,
        timestamp: new Date().toISOString(),
      },
    });
    return;
  }

  // 3. Global Status Code override
  if (globalState.globalStatusCode && globalState.globalStatusCode !== 200) {
    const sc = globalState.globalStatusCode;
    res.status(sc).json({
      error: {
        code: `GLOBAL_STATUS_OVERRIDE_${sc}`,
        message: `Global status override active returning HTTP ${sc}.`,
        status: sc,
        requestId,
        timestamp: new Date().toISOString(),
      },
    });
    return;
  }

  // 4. Endpoint-specific Status Code override
  if (epConfig && epConfig.mode !== 'HEALTHY' && epConfig.statusCode && epConfig.statusCode >= 400) {
    res.status(epConfig.statusCode).json({
      error: {
        code: `SIMULATED_${epConfig.statusCode}`,
        message: epConfig.failure?.errorMessage || `Endpoint configured to return simulated status ${epConfig.statusCode}.`,
        status: epConfig.statusCode,
        requestId,
        timestamp: new Date().toISOString(),
      },
    });
    return;
  }

  // 5. Authentication Simulation
  if (epConfig && (epConfig.mode === 'AUTH_REQUIRED' || (epConfig.auth?.required && epConfig.mode !== 'HEALTHY'))) {
    const authType = epConfig.auth.type;
    let authValid = false;

    if (authType === 'bearer') {
      const authHeader = req.headers['authorization'];
      const expectedToken = epConfig.auth.expectedToken || config.defaultAuthToken;
      if (authHeader && authHeader.startsWith('Bearer ')) {
        const token = authHeader.substring(7).trim();
        if (token === expectedToken) {
          authValid = true;
        }
      }
    } else if (authType === 'basic') {
      const authHeader = req.headers['authorization'];
      if (authHeader && authHeader.startsWith('Basic ')) {
        const b64 = authHeader.substring(6).trim();
        const decoded = Buffer.from(b64, 'base64').toString('utf-8');
        const [u, p] = decoded.split(':');
        const expectedUser = epConfig.auth.username || config.defaultBasicAuth.username;
        const expectedPass = epConfig.auth.password || config.defaultBasicAuth.password;
        if (u === expectedUser && p === expectedPass) {
          authValid = true;
        }
      }
    } else if (authType === 'apikey') {
      const apiKeyHeader = req.headers['x-api-key'] || req.query.apiKey;
      const expectedKey = epConfig.auth.apiKey || config.defaultApiKey;
      if (apiKeyHeader === expectedKey) {
        authValid = true;
      }
    }

    if (!authValid) {
      res.status(401).json({
        error: {
          code: 'UNAUTHORIZED',
          message: `Authentication required for endpoint (${authType.toUpperCase()}). Invalid or missing credentials.`,
          status: 401,
          requestId,
          timestamp: new Date().toISOString(),
        },
      });
      return;
    }
  }

  // 6. Rate Limiting Simulation
  if (epConfig && epConfig.mode !== 'HEALTHY' && epConfig.rateLimit && epConfig.rateLimit.enabled) {
    const clientKey = `${req.ip}_${matchedEp?.id || 'gen'}`;
    const rl = simulationService.checkRateLimit(
      clientKey,
      epConfig.rateLimit.maxRequests,
      epConfig.rateLimit.windowSeconds
    );

    res.setHeader('X-RateLimit-Limit', epConfig.rateLimit.maxRequests);
    res.setHeader('X-RateLimit-Remaining', rl.remaining);
    res.setHeader('X-RateLimit-Reset', Math.ceil(rl.resetTime / 1000));

    if (!rl.allowed) {
      res.status(429).json({
        error: {
          code: 'RATE_LIMIT_EXCEEDED',
          message: `Too Many Requests. Rate limit of ${epConfig.rateLimit.maxRequests} requests per ${epConfig.rateLimit.windowSeconds}s reached.`,
          status: 429,
          requestId,
          timestamp: new Date().toISOString(),
        },
      });
      return;
    }
  }

  // 7. Database Simulation Mode
  if (epConfig && epConfig.mode !== 'HEALTHY' && epConfig.database) {
    if (epConfig.database.mode === 'failure') {
      res.status(500).json({
        error: {
          code: 'DATABASE_CONNECTION_ERROR',
          message: 'Simulated database cluster timeout: Connection pool exhausted.',
          status: 500,
          requestId,
          timestamp: new Date().toISOString(),
        },
      });
      return;
    }
  }

  // 8. Gateway Simulation Mode
  if (epConfig && epConfig.mode !== 'HEALTHY' && epConfig.gateway) {
    if (epConfig.gateway.mode === 'bad_gateway') {
      res.status(502).json({
        error: {
          code: 'BAD_GATEWAY',
          message: '502 Bad Gateway: Upstream service did not send a valid HTTP response.',
          status: 502,
          requestId,
          timestamp: new Date().toISOString(),
        },
      });
      return;
    }
    if (epConfig.gateway.mode === 'gateway_timeout') {
      res.status(504).json({
        error: {
          code: 'GATEWAY_TIMEOUT',
          message: '504 Gateway Timeout: Reverse proxy timed out waiting for microservice response.',
          status: 504,
          requestId,
          timestamp: new Date().toISOString(),
        },
      });
      return;
    }
  }

  // 9. Failure Rate / Intermittent Simulation
  const failureConfig = epConfig?.failure;
  if (epConfig?.mode !== 'HEALTHY' && failureConfig && failureConfig.enabled && failureConfig.ratePercent > 0) {
    const roll = Math.random() * 100;
    if (roll < failureConfig.ratePercent) {
      const code = failureConfig.statusCode || 500;
      res.status(code).json({
        error: {
          code: `SIMULATED_FAILURE_${code}`,
          message: failureConfig.errorMessage || `Simulated failure occurred (rate: ${failureConfig.ratePercent}%).`,
          status: code,
          requestId,
          timestamp: new Date().toISOString(),
        },
      });
      return;
    }
  }

  // Global Failure Rate check
  if (globalState.globalFailureRate > 0) {
    const roll = Math.random() * 100;
    if (roll < globalState.globalFailureRate) {
      res.status(500).json({
        error: {
          code: 'GLOBAL_FAILURE_TRIGGERED',
          message: `Global random failure injected (${globalState.globalFailureRate}% target rate).`,
          status: 500,
          requestId,
          timestamp: new Date().toISOString(),
        },
      });
      return;
    }
  }

  // 10. Latency Simulation
  let delayMs = 0;

  // Add direct latency from query param or header (capped at 30s)
  if (directLatencyMs && directLatencyMs > 0) {
    delayMs += Math.min(directLatencyMs, 30000);
  }

  // Add global latency
  if (globalState.globalLatencyMs > 0) {
    delayMs += globalState.globalLatencyMs;
  }

  // Add database slowdown latency
  if (epConfig?.database?.mode === 'slow') {
    delayMs += epConfig.database.addedLatencyMs || 1500;
  }

  // Add endpoint-specific latency
  if (epConfig && epConfig.latency) {
    if (epConfig.latency.type === 'fixed' && epConfig.latency.fixedMs) {
      delayMs += epConfig.latency.fixedMs;
    } else if (epConfig.latency.type === 'random' && epConfig.latency.minMs !== undefined && epConfig.latency.maxMs !== undefined) {
      const min = epConfig.latency.minMs;
      const max = epConfig.latency.maxMs;
      delayMs += Math.floor(min + Math.random() * (max - min));
    } else if (epConfig.latency.type === 'timeout') {
      delayMs += epConfig.latency.timeoutMs || 15000;
    }
  }

  if (delayMs > 0) {
    await new Promise(resolve => setTimeout(resolve, delayMs));
  }

  next();
};

function transformToSchemaV2(data: any): any {
  if (Array.isArray(data)) {
    return data.map(transformToSchemaV2);
  }
  if (data && typeof data === 'object') {
    // If it's a paginated wrapper with items
    if (data.items && Array.isArray(data.items)) {
      return {
        ...data,
        items: data.items.map(transformItemToV2),
        schemaVersion: 'v2',
      };
    }
    return transformItemToV2(data);
  }
  return data;
}

function transformItemToV2(item: any): any {
  if (!item || typeof item !== 'object') return item;
  const v2: any = { ...item };
  if ('name' in v2) {
    v2.productName = v2.name;
    delete v2.name;
  }
  if ('price' in v2) {
    v2.amount = v2.price;
    delete v2.price;
  }
  if ('stock' in v2) {
    v2.inventoryCount = v2.stock;
    delete v2.stock;
  }
  v2.apiVersion = 'v2';
  return v2;
}

function getStandardErrorMessage(status: number): string {
  switch (status) {
    case 400: return 'Bad Request: The request was invalid or malformed.';
    case 401: return 'Unauthorized: Valid authentication credentials are required.';
    case 403: return 'Forbidden: You do not have permission to access this resource.';
    case 404: return 'Not Found: The target resource does not exist on this server.';
    case 405: return 'Method Not Allowed: The HTTP method is not supported for this endpoint.';
    case 408: return 'Request Timeout: The server timed out waiting for the request.';
    case 409: return 'Conflict: Request conflicts with the current state of the resource.';
    case 422: return 'Unprocessable Entity: Payload contains semantic validation errors.';
    case 429: return 'Too Many Requests: Rate limit exceeded. Please back off and retry later.';
    case 500: return 'Internal Server Error: An unexpected fault was encountered on the server.';
    case 502: return 'Bad Gateway: Invalid response received from upstream microservice.';
    case 503: return 'Service Unavailable: Service is currently down or undergoing maintenance.';
    case 504: return 'Gateway Timeout: Upstream backend service failed to respond in time.';
    default: return `Simulated HTTP Error ${status}.`;
  }
}
